const OBS_MSG_PREFIXES = ["Connected - ", "Error: ", "Embedding: ", "Delete folder \"", "Delete image \""];

(function() {
  var saved = localStorage.getItem('obs_lang');
  var detected = (navigator.language || navigator.userLanguage || 'en').slice(0, 2).toLowerCase();
  var lang = saved || (OBS_TRANSLATIONS[detected] ? detected : 'en');
  window.OBS_LANG = lang;
  window.t = function(key) {
    return (OBS_TRANSLATIONS[lang] && OBS_TRANSLATIONS[lang][key]) ||
           (OBS_TRANSLATIONS['en'] && OBS_TRANSLATIONS['en'][key]) ||
           key;
  };
  window.tr = function(text) {
    if (lang === 'en' || text == null) return text;
    if (Object.prototype.hasOwnProperty.call(OBS_MESSAGES, text)) return OBS_MESSAGES[text];
    for (var i = 0; i < OBS_MSG_PREFIXES.length; i++) {
      var p = OBS_MSG_PREFIXES[i];
      if (text.indexOf(p) === 0) return OBS_MESSAGES[p] + text.slice(p.length);
    }
    return text;
  };
  window.setLang = function(l) {
    if (OBS_TRANSLATIONS[l]) {
      localStorage.setItem('obs_lang', l);
      location.reload();
    }
  };
})();